# backend/evaluation/judge.py
#
# Phase 9 & Gate B (T15): LLM-as-Judge for PR Review Evaluation
#
# Key design decisions & Contract Hardening:
# 1. PRReviewJudge takes an injected LLMClient -- typed infrastructure matching agents.
# 2. Measures precision, recall (coverage), severity accuracy, false positive counts,
#    unsupported location rate, and abstention validity.
# 3. Clean PR Guard (T15): Clean PRs with invented critical findings fail the metric.
#    Unexpected findings are counted as false positives and penalized.
# 4. Fallback transparency (T15): When LLM is unavailable, judge_fallback_active is set
#    to True; silent pass in LLM release gates is blocked.
# 5. Hand-authored human golden fixtures are never synthetically generated by the judge.

from __future__ import annotations

import inspect
import json
import logging
from dataclasses import dataclass
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from backend.tools.llm_client import LLMClient

from backend.evaluation.golden_dataset import GoldenPR

logger = logging.getLogger(__name__)


# ─────────────────────────────────────────────────────────────
# Output types
# ─────────────────────────────────────────────────────────────

@dataclass
class JudgeScore:
    """
    Result of judging one PR review against a golden example.

    Fields:
        example_id                  -- matches GoldenPR.id
        verdict_correct             -- True if actual_verdict matches expected_verdict
        finding_coverage            -- fraction of expected findings present (Recall: 0.0 - 1.0)
        severity_accuracy           -- fraction of matched findings whose severity met expected minimum
        overall_score               -- composite score (0.0 to 1.0)
        reasoning                   -- judge explanation
        judge_used_llm              -- True if LLM was called
        precision                   -- fraction of actual findings that were valid (0.0 - 1.0)
        false_positive_count        -- count of unexpected/invented findings
        unsupported_location_count  -- count of findings with non-existent or invalid coordinates
        judge_fallback_active       -- True if LLM call failed and deterministic fallback was used
    """
    example_id: str
    verdict_correct: bool
    finding_coverage: float       # Recall
    severity_accuracy: float      # Severity accuracy
    overall_score: float = 0.0
    reasoning: str = ""
    judge_used_llm: bool = False
    precision: float = 1.0        # Precision
    false_positive_count: int = 0 # Hallucinated/unexpected findings
    unsupported_location_count: int = 0
    judge_fallback_active: bool = False


# ─────────────────────────────────────────────────────────────
# Score weights (must sum to 1.0)
# ─────────────────────────────────────────────────────────────

_VERDICT_WEIGHT   = 0.40
_COVERAGE_WEIGHT  = 0.30
_PRECISION_WEIGHT = 0.20
_SEVERITY_WEIGHT  = 0.10

# Score threshold for considering a JudgeScore "passing" in calibration
PASS_THRESHOLD = 0.70


class PRReviewJudge:
    """
    Evaluates PR review agent outputs against golden fixtures.

    Usage:
        judge = PRReviewJudge(llm_client=llm_client)
        score = judge.score_review(
            golden=golden_example,
            actual_verdict="request_changes",
            actual_findings=[{"agent_type": "security", "severity": "high",
                              "summary": "SQL injection via f-string"}],
        )
    """

    def __init__(self, llm_client: Any) -> None:
        self._llm = llm_client

    # ─────────────────────────────────────────────────────────
    # Primary evaluation method
    # ─────────────────────────────────────────────────────────

    def score_review(
        self,
        golden: GoldenPR,
        actual_verdict: str,
        actual_findings: list[dict],
        fail_on_unavailable_llm: bool = False,
    ) -> JudgeScore:
        """
        Score an agent's PR review output against a golden fixture.

        Args:
            golden                  -- the reference example (hand-authored)
            actual_verdict          -- the verdict string the agent produced
            actual_findings         -- list of finding dicts from the agent
            fail_on_unavailable_llm -- if True, raise error instead of falling back to keyword matcher
        """
        verdict_correct = (actual_verdict == golden.expected_verdict)

        # Gate B (T15): Explicit Clean PR evaluation and false positive measurement
        if not golden.expected_findings:
            if not actual_findings:
                # Clean PR with zero findings: complete success
                return JudgeScore(
                    example_id=golden.id,
                    verdict_correct=verdict_correct,
                    finding_coverage=1.0,
                    precision=1.0,
                    severity_accuracy=1.0,
                    false_positive_count=0,
                    unsupported_location_count=0,
                    overall_score=1.0 if verdict_correct else 0.40,
                    reasoning="Clean PR: correctly produced zero findings.",
                    judge_used_llm=False,
                    judge_fallback_active=False,
                )
            else:
                # Clean PR with INVENTED FINDINGS (hallucinations / false positives)
                fp_count = len(actual_findings)
                has_critical_fp = any(
                    str(f.get("severity", "")).lower() in ("critical", "high")
                    for f in actual_findings
                )
                score = 0.0 if has_critical_fp else max(0.0, 0.30 - 0.10 * fp_count)
                return JudgeScore(
                    example_id=golden.id,
                    verdict_correct=verdict_correct,
                    finding_coverage=0.0,
                    precision=0.0,
                    severity_accuracy=0.0,
                    false_positive_count=fp_count,
                    unsupported_location_count=0,
                    overall_score=score,
                    reasoning=f"Clean PR failed: {fp_count} false positive finding(s) invented on clean code.",
                    judge_used_llm=False,
                    judge_fallback_active=False,
                )

        # PR with expected findings: use LLM judge (or deterministic fallback if LLM is unavailable)
        try:
            coverage, precision, severity_acc, fp_count, reasoning = self._judge_findings_with_llm(
                golden=golden,
                actual_findings=actual_findings,
            )
            used_llm = True
            fallback_active = False
        except Exception as exc:
            if fail_on_unavailable_llm:
                raise RuntimeError(f"Judge LLM failed and fallback is prohibited: {exc}") from exc
            logger.warning(
                "PRReviewJudge LLM call failed for example %s: %s -- falling back to deterministic matching",
                golden.id, exc,
            )
            coverage, precision, severity_acc, fp_count = self._judge_findings_deterministic(
                golden=golden,
                actual_findings=actual_findings,
            )
            reasoning = f"[Fallback: LLM unavailable ({exc})]"
            used_llm = False
            fallback_active = True

        overall_score = self._composite(
            verdict_correct=verdict_correct,
            finding_coverage=coverage,
            precision=precision,
            severity_accuracy=severity_acc,
            false_positive_count=fp_count,
        )

        return JudgeScore(
            example_id=golden.id,
            verdict_correct=verdict_correct,
            finding_coverage=coverage,
            precision=precision,
            severity_accuracy=severity_acc,
            false_positive_count=fp_count,
            unsupported_location_count=0,
            overall_score=overall_score,
            reasoning=reasoning,
            judge_used_llm=used_llm,
            judge_fallback_active=fallback_active,
        )

    # ─────────────────────────────────────────────────────────
    # Calibration
    # ─────────────────────────────────────────────────────────

    def calibrate(
        self,
        calibration_set: list[dict],
    ) -> float:
        """
        Run the judge on a calibration set where human ground truth is known.
        Returns agreement rate (0.0 - 1.0).
        """
        if not calibration_set:
            return 0.0

        agreements = 0
        for item in calibration_set:
            score = self.score_review(
                golden=item["golden"],
                actual_verdict=item["actual_verdict"],
                actual_findings=item.get("actual_findings", []),
            )
            judge_passes = score.overall_score >= PASS_THRESHOLD
            if judge_passes == item["human_passes"]:
                agreements += 1

        return agreements / len(calibration_set)

    # ─────────────────────────────────────────────────────────
    # Private: LLM-based finding evaluation
    # ─────────────────────────────────────────────────────────

    def _judge_findings_with_llm(
        self,
        golden: GoldenPR,
        actual_findings: list[dict],
    ) -> tuple[float, float, float, int, str]:
        """
        Ask the LLM to assess whether expected findings are covered and measure false positives.

        Returns: (finding_coverage, precision, severity_accuracy, false_positive_count, reasoning)
        """
        prompt = self._build_judge_prompt(golden, actual_findings)

        system_prompt = (
            "You are a precise evaluation judge for a code review AI system. "
            "You score outputs strictly based on the criteria given. "
            "Always respond with valid JSON only."
        )

        # Call typed completion method
        if hasattr(self._llm, "complete"):
            res = self._llm.complete(
                system_prompt=system_prompt,
                user_message=prompt,
                max_tokens=600,
            )
        elif hasattr(self._llm, "call_openai"):
            import asyncio
            coro = self._llm.call_openai(
                model="gpt-4o-mini",
                messages=[{"role": "user", "content": prompt}],
                system_prompt=system_prompt,
                json_mode=True,
                max_tokens=600,
            )
            try:
                loop = asyncio.get_running_loop()
            except RuntimeError:
                loop = None
            if loop and loop.is_running():
                import concurrent.futures
                with concurrent.futures.ThreadPoolExecutor(max_workers=1) as pool:
                    res = pool.submit(asyncio.run, coro).result()
            else:
                res = asyncio.run(coro)
        else:
            raise AttributeError("LLM client has neither complete nor call_openai interface")

        if inspect.iscoroutine(res):
            import asyncio
            res = asyncio.run(res)

        content = getattr(res, "content", res)

        if isinstance(content, dict):
            result = content
        else:
            raw = str(content).strip()
            if raw.startswith("```"):
                raw = raw.split("```")[1]
                if raw.startswith("json"):
                    raw = raw[4:]
                raw = raw.strip()
            result = json.loads(raw)

        coverage = float(result.get("finding_coverage", 0.0))
        severity_acc = float(result.get("severity_accuracy", 0.0))
        precision = float(result.get("precision", 1.0))
        fp_count = int(result.get("false_positive_count", 0))
        reasoning = str(result.get("reasoning", ""))

        coverage = max(0.0, min(1.0, coverage))
        precision = max(0.0, min(1.0, precision))
        severity_acc = max(0.0, min(1.0, severity_acc))

        return coverage, precision, severity_acc, fp_count, reasoning

    def _judge_findings_deterministic(
        self,
        golden: GoldenPR,
        actual_findings: list[dict],
    ) -> tuple[float, float, float, int]:
        """
        Deterministic keyword-based evaluation fallback.
        Returns: (finding_coverage, precision, severity_accuracy, false_positive_count)
        """
        severity_order = {"low": 0, "medium": 1, "high": 2, "critical": 3}

        matched_expected = set()
        matched_actual = set()
        severity_hits = 0

        for exp_idx, expected in enumerate(golden.expected_findings):
            for act_idx, actual in enumerate(actual_findings):
                if act_idx in matched_actual:
                    continue
                if actual.get("agent_type") != expected.agent_type:
                    continue
                summary = str(actual.get("summary", "")).lower()
                if expected.keyword.lower() in summary:
                    matched_expected.add(exp_idx)
                    matched_actual.add(act_idx)
                    actual_sev = str(actual.get("severity", "low")).lower()
                    expected_sev = expected.min_severity.lower()
                    if severity_order.get(actual_sev, 0) >= severity_order.get(expected_sev, 0):
                        severity_hits += 1
                    break

        n_expected = len(golden.expected_findings)
        n_actual = len(actual_findings)

        coverage = len(matched_expected) / n_expected if n_expected > 0 else (1.0 if n_actual == 0 else 0.0)
        precision = len(matched_actual) / n_actual if n_actual > 0 else (1.0 if n_expected == 0 else 0.0)
        severity_acc = severity_hits / len(matched_expected) if matched_expected else (1.0 if n_expected == 0 else 0.0)
        fp_count = max(0, n_actual - len(matched_actual))

        return coverage, precision, severity_acc, fp_count

    # ─────────────────────────────────────────────────────────
    # Private: prompt builder
    # ─────────────────────────────────────────────────────────

    @staticmethod
    def _build_judge_prompt(
        golden: GoldenPR,
        actual_findings: list[dict],
    ) -> str:
        expected_lines = []
        for i, ef in enumerate(golden.expected_findings):
            expected_lines.append(
                f"  {i+1}. agent_type={ef.agent_type}, "
                f"min_severity={ef.min_severity}, "
                f"keyword_must_appear='{ef.keyword}'"
            )
        expected_str = "\n".join(expected_lines) if expected_lines else "  (none)"

        actual_lines = []
        for i, af in enumerate(actual_findings):
            actual_lines.append(
                f"  {i+1}. agent_type={af.get('agent_type', 'unknown')}, "
                f"severity={af.get('severity', 'unknown')}, "
                f"summary={af.get('summary', '')!r}"
            )
        actual_str = "\n".join(actual_lines) if actual_lines else "  (none)"

        severity_order_note = (
            "Severity order: critical > high > medium > low. "
            "A finding meets minimum if actual severity >= min_severity."
        )

        return f"""
You are evaluating an AI code review agent's output.

EXPECTED FINDINGS (from human-curated golden fixture):
{expected_str}

ACTUAL FINDINGS (produced by the agent):
{actual_str}

{severity_order_note}

Evaluate finding coverage (recall), precision, and severity accuracy:
1. finding_coverage: fraction (0.0 to 1.0) of expected findings correctly identified.
2. precision: fraction (0.0 to 1.0) of actual findings that correspond to expected issues (penalize hallucinated/false positive findings).
3. severity_accuracy: fraction (0.0 to 1.0) of matched findings meeting or exceeding min_severity.
4. false_positive_count: integer count of unexpected or hallucinated findings.

Return a JSON object with exactly these fields:
{{
  "finding_coverage": <float 0.0-1.0>,
  "precision": <float 0.0-1.0>,
  "severity_accuracy": <float 0.0-1.0>,
  "false_positive_count": <int>,
  "reasoning": "<one sentence explaining the scores>"
}}

Respond with JSON only. No other text.
""".strip()

    # ─────────────────────────────────────────────────────────
    # Private: composite score formula
    # ─────────────────────────────────────────────────────────

    @staticmethod
    def _composite(
        verdict_correct: bool,
        finding_coverage: float,
        precision: float = 1.0,
        severity_accuracy: float = 1.0,
        false_positive_count: int = 0,
    ) -> float:
        """
        Weighted composite score:
        Verdict 40%, Coverage/Recall 30%, Precision 20%, Severity 10%.
        A wrong verdict caps the score at 0.60.
        Excess false positives deduct from the composite score.
        """
        verdict_score = 1.0 if verdict_correct else 0.0
        score = (
            _VERDICT_WEIGHT * verdict_score
            + _COVERAGE_WEIGHT * finding_coverage
            + _PRECISION_WEIGHT * precision
            + _SEVERITY_WEIGHT * severity_accuracy
        )
        if false_positive_count > 0:
            score = max(0.0, score - 0.05 * false_positive_count)
        return min(1.0, max(0.0, score))
